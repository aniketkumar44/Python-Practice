#odd number(0 to 20)
for i in range(0,20):
    if (i%2!=0):
        print(i)
print("-"*5)
#even number(0 to 20)
for i in range(0,20):
    if (i%2==0):
        print(i)
print("-"*5)
#using range
for i in range(10): #range(stop)
    print(i)
print("-"*5)
for i in range(2,10): #range(start,stop)
    print(i)
print("-"*5)
# even number
for i in range(2,101,2): #range(star,stop,step)
    print(i)
print("-"*5)
